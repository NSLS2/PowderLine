#!/usr/bin/env python3
"""Draw the examples gallery's fit figures from the committed fit profiles.

Every example with a committed ``fit_profile.txt`` gets one small SVG under
``docs/_generated/examples/``:

* ``examples/<name>/output/fit_profile.txt`` -> ``<name>.svg`` (the GSAS-II recipe);
* ``examples/<name>/<engine>/output/fit_profile.txt`` -> ``<name>_<engine>.svg``.

Each figure shows the observed pattern (grey), the calculated pattern (blue)
and the difference curve (orange, offset below) over the fit window, with a
2θ axis. The colours are mid-tones and the background is transparent, so a
figure reads on the light and on the dark theme.

The script is pure Python (no matplotlib, no engine), so it runs in the default
environment. Its output is byte-deterministic on every platform: the profiles
are reduced to a fixed number of columns (the minimum and maximum of each, so
peak heights survive), coordinates are rounded to 0.1 px, and files are
written as UTF-8 with ``\\n`` newlines::

    python scripts/gen_example_figures.py            # rewrite the figures
    python scripts/gen_example_figures.py --check    # exit 1 if a figure is stale, missing or extra

Run it after a committed fit profile changes and commit the figures with the
change. The figures are drawn from the committed references only; the script
never runs a refinement.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXAMPLES = ROOT / "examples"
OUT_DIR = ROOT / "docs" / "_generated" / "examples"

HEADER = "<!-- generated by scripts/gen_example_figures.py; do not edit -->"

#: Engine subfolders of an example, in output order. The top-level recipe is GSAS-II's.
ENGINE_DIRS = ("easydiffraction", "topas")
ENGINE_LABELS = {"": "GSAS-II", "easydiffraction": "easydiffraction", "topas": "TOPAS"}

# Canvas and plot area (px).
WIDTH, HEIGHT = 640, 300
LEFT, RIGHT = 40.0, 624.0
TOP, BOTTOM = 12.0, 250.0
BIN_PX = 2.0  # one min/max pair per 2 px column

# Mid-tone colours, legible on a light and on a dark background.
OBS = "#8c8c8c"
CALC = "#3d7fd9"
DIFF = "#e07b28"
AXIS = "#8c8c8c"


def profiles() -> list[tuple[str, str, str, Path]]:
    """``(figure name, example, engine folder, fit profile)`` for every committed fit profile, in a fixed order."""
    found = []
    for example in sorted(p for p in EXAMPLES.iterdir() if p.is_dir() and p.name.startswith("example_")):
        if example.name == "example_template":
            continue
        for engine in ("",) + ENGINE_DIRS:
            path = (example / engine / "output" / "fit_profile.txt") if engine else (example / "output" / "fit_profile.txt")
            if path.is_file():
                found.append((f"{example.name}_{engine}" if engine else example.name, example.name, engine, path))
    return found


def without_profile() -> list[str]:
    """The example recipes (``<name>`` or ``<name>/<engine>``) that have no committed fit profile."""
    missing = []
    for example in sorted(p for p in EXAMPLES.iterdir() if p.is_dir() and p.name.startswith("example_")):
        if example.name == "example_template":
            continue
        for engine in ("",) + ENGINE_DIRS:
            base = example / engine if engine else example
            if (base / "input.json").is_file() and not (base / "output" / "fit_profile.txt").is_file():
                missing.append(f"{example.name}/{engine}" if engine else example.name)
    return missing


def read_profile(path: Path) -> dict[str, list[float]]:
    """The columns of a fit profile by their header names (tab-separated, one header line)."""
    lines = path.read_text(encoding="utf-8").splitlines()
    names = lines[0].split()
    columns: dict[str, list[float]] = {n: [] for n in names}
    for line in lines[1:]:
        if not line.strip():
            continue
        for name, field in zip(names, line.split()):
            columns[name].append(float(field))
    for needed in ("two_theta", "y_obs", "y_calc"):
        if needed not in columns:
            raise SystemExit(f"{path}: no '{needed}' column in the header {names}")
    if "y_diff" not in columns:
        columns["y_diff"] = [o - c for o, c in zip(columns["y_obs"], columns["y_calc"])]
    return columns


def fit_window(columns: dict[str, list[float]]) -> range:
    """The rows of the fit window: GSAS-II writes the whole pattern with ``y_calc`` 0 outside it."""
    calc = columns["y_calc"]
    inside = [i for i, v in enumerate(calc) if v != 0.0]
    if not inside:
        return range(len(calc))
    return range(inside[0], inside[-1] + 1)


def envelope(xs: list[float], ys: list[float], x0: float, x1: float, bins: int) -> list[tuple[float, float]]:
    """Reduce a curve to the minimum and maximum of each x column, in x order, so peaks keep their height."""
    columns: list[list[tuple[float, float]]] = [[] for _ in range(bins)]
    span = x1 - x0
    for x, y in zip(xs, ys):
        k = int((x - x0) / span * bins) if span > 0 else 0
        columns[min(max(k, 0), bins - 1)].append((x, y))
    out: list[tuple[float, float]] = []
    for pts in columns:
        if not pts:
            continue
        lo = min(pts, key=lambda p: p[1])
        hi = max(pts, key=lambda p: p[1])
        out.extend(sorted({lo, hi}))
    return out


def fmt(v: float) -> str:
    s = f"{v:.1f}"
    return "0.0" if s == "-0.0" else s


def nice_step(span: float, max_ticks: int = 8) -> float:
    for step in (0.1, 0.2, 0.25, 0.5, 1.0, 2.0, 2.5, 5.0, 10.0, 20.0, 25.0, 50.0, 100.0):
        if span / step <= max_ticks:
            return step
    return 100.0


def tick_label(v: float, step: float) -> str:
    return f"{v:.0f}" if step >= 1 else f"{v:.1f}" if step * 10 == int(step * 10) else f"{v:.2f}"


def svg(example: str, engine: str, path: Path) -> str:
    cols = read_profile(path)
    rows = fit_window(cols)
    tth = [cols["two_theta"][i] for i in rows]
    obs = [cols["y_obs"][i] for i in rows]
    calc = [cols["y_calc"][i] for i in rows]
    diff = [cols["y_diff"][i] for i in rows]
    x0, x1 = tth[0], tth[-1]

    # One intensity scale for all three curves; the difference curve sits below the patterns.
    top_hi = max(max(obs), max(calc))
    top_lo = min(min(obs), min(calc))
    d_hi, d_lo = max(diff), min(diff)
    gap = 0.04 * (top_hi - top_lo)
    zero = top_lo - gap - d_hi  # the difference curve's zero, in intensity units
    y_hi, y_lo = top_hi, zero + d_lo
    if y_hi == y_lo:
        y_hi += 1.0

    def px(x: float) -> float:
        return LEFT + (x - x0) / (x1 - x0) * (RIGHT - LEFT)

    def py(y: float) -> float:
        return BOTTOM - (y - y_lo) / (y_hi - y_lo) * (BOTTOM - TOP)

    bins = int((RIGHT - LEFT) / BIN_PX)

    def polyline(ys: list[float], colour: str, width: str, offset: float = 0.0) -> str:
        pts = envelope(tth, ys, x0, x1, bins)
        coords = " ".join(f"{fmt(px(x))},{fmt(py(y + offset))}" for x, y in pts)
        return (f'<polyline fill="none" stroke="{colour}" stroke-width="{width}" '
                f'stroke-linejoin="round" points="{coords}"/>')

    label = ENGINE_LABELS[engine]
    source = path.relative_to(ROOT).as_posix()

    step = nice_step(x1 - x0)
    first = step * int(x0 / step + (0 if x0 % step == 0 else 1))
    ticks = []
    t = first
    while t <= x1 + 1e-9:
        ticks.append(t)
        t = round(t + step, 6)

    out = [
        HEADER,
        f"<!-- source: {source} -->",
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{WIDTH}" height="{HEIGHT}" '
        f'viewBox="0 0 {WIDTH} {HEIGHT}" role="img">',
        f"<title>{example} ({label}): observed (grey), calculated (blue) and difference (orange) "
        f"over the fit window</title>",
        f'<line x1="{fmt(LEFT)}" y1="{fmt(BOTTOM + 4)}" x2="{fmt(RIGHT)}" y2="{fmt(BOTTOM + 4)}" '
        f'stroke="{AXIS}" stroke-width="1"/>',
        f'<line x1="{fmt(LEFT - 4)}" y1="{fmt(TOP)}" x2="{fmt(LEFT - 4)}" y2="{fmt(BOTTOM)}" '
        f'stroke="{AXIS}" stroke-width="1"/>',
    ]
    for t in ticks:
        x = fmt(px(t))
        out.append(f'<line x1="{x}" y1="{fmt(BOTTOM + 4)}" x2="{x}" y2="{fmt(BOTTOM + 9)}" '
                   f'stroke="{AXIS}" stroke-width="1"/>')
    out.append(f'<g fill="{AXIS}" font-family="sans-serif" font-size="12" text-anchor="middle">')
    for t in ticks:
        out.append(f'<text x="{fmt(px(t))}" y="{fmt(BOTTOM + 22)}">{tick_label(t, step)}</text>')
    out.append(f'<text x="{fmt((LEFT + RIGHT) / 2)}" y="{fmt(BOTTOM + 42)}">2θ (°)</text>')
    out.append(f'<text transform="translate({fmt(LEFT - 12)},{fmt((TOP + BOTTOM) / 2)}) rotate(-90)">'
               f"Intensity</text>")
    out.append("</g>")
    out.append(f'<line x1="{fmt(LEFT)}" y1="{fmt(py(zero))}" x2="{fmt(RIGHT)}" y2="{fmt(py(zero))}" '
               f'stroke="{AXIS}" stroke-width="0.5" stroke-dasharray="3 3"/>')
    out.append(polyline(obs, OBS, "2"))
    out.append(polyline(calc, CALC, "1"))
    out.append(polyline(diff, DIFF, "1", offset=zero))
    out.append("</svg>")
    return "\n".join(out) + "\n"


def figures() -> dict[str, str]:
    return {f"{name}.svg": svg(example, engine, path) for name, example, engine, path in profiles()}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if a committed figure differs from the fit profiles, or is missing or extra")
    ap.add_argument("--out-dir", type=Path, default=OUT_DIR)
    args = ap.parse_args(argv)
    wanted = figures()
    skipped = without_profile()
    try:
        shown = args.out_dir.resolve().relative_to(Path.cwd().resolve()).as_posix()
    except ValueError:
        shown = str(args.out_dir)

    if not args.check:
        args.out_dir.mkdir(parents=True, exist_ok=True)
        for name, text in wanted.items():
            with open(args.out_dir / name, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text)
            print(f"wrote {shown}/{name}")
        for extra in sorted(p.name for p in args.out_dir.glob("*.svg") if p.name not in wanted):
            print(f"note: {shown}/{extra} has no fit profile behind it; delete it", file=sys.stderr)
        if skipped:
            print("no committed fit profile (no figure): " + ", ".join(skipped))
        return 0

    stale, missing = [], []
    for name, text in wanted.items():
        path = args.out_dir / name
        if not path.is_file():
            missing.append(name)
        elif path.read_bytes() != text.encode("utf-8"):
            stale.append(name)
    extra = sorted(p.name for p in args.out_dir.glob("*.svg") if p.name not in wanted) if args.out_dir.is_dir() else []
    if stale or missing or extra:
        parts = [f"{label}: " + ", ".join(names)
                 for label, names in (("stale", stale), ("missing", missing), ("extra", extra)) if names]
        print(f"figures-check: under {shown}, " + "; ".join(parts)
              + " (regenerate with scripts/gen_example_figures.py; delete an extra figure)", file=sys.stderr)
        return 1
    print(f"figures-check: {len(wanted)} figures under {shown} match the committed fit profiles "
          f"({len(skipped)} example recipes have none)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
