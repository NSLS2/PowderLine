#!/usr/bin/env python3
"""Generate the docs' engine-behaviour entries, ID index and known issues from the public catalogue.

Every ``EB-NN`` (engine behaviour) and ``KI-NN`` (known issue) id that PowderLine
prints, or that the docs cite, must be look-up-able. The public fields of each
entry live in two data files:

* ``docs/catalog/engine_behaviour.yaml`` -- one entry per ``EB-NN``;
* ``docs/catalog/known_issues.yaml`` -- one entry per ``KI-NN``.

This script validates both and writes MyST fragments that the pages pull in
with ``{include}``:

* ``docs/_generated/eb_<engine>.md`` (``gsasii``, ``topas``,
  ``easydiffraction``, ``all``) -- the entries of one engine, grouped by topic,
  each with a label ``(eb-nn)=`` so ``{ref}`EB-87 <eb-87>``` links from any page;
* ``docs/_generated/ids.md`` -- the ID index: every EB, then every KI;
* ``docs/_generated/known_issues.md`` -- the KI entries, grouped by status,
  each with a label ``(ki-nn)=``.

Engine-free. It needs PyYAML, and ``powderline`` importable (``PYTHONPATH=src``
or the pixi environment) for the ``you_see`` check::

    pixi run python scripts/gen_catalog.py   # rewrite the fragments
    pixi run catalog-check                   # exit 1 if they are stale, or an id has no entry

``--check`` also:

* scans every text file under ``src/``, ``docs/``, ``examples/``, ``scripts/``
  and ``tests/``, and the top-level ``*.md`` files, for ``EB-<digits>`` and
  ``KI-<digits>``, and fails naming any id the catalogue does not hold. It
  skips ``docs/catalog/``, the fragments this script writes, and build
  directories;
* fails on an ``eb_*.md`` fragment under ``docs/_generated/`` that this script
  does not write.

Every ``you_see`` item must be a warning code, a failure reason, or start with
"validation error".

Edit the YAML, run the script, and commit the YAML and the fragments together.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CATALOG_DIR = ROOT / "docs" / "catalog"
OUT_DIR = ROOT / "docs" / "_generated"
EB_FILE = CATALOG_DIR / "engine_behaviour.yaml"
KI_FILE = CATALOG_DIR / "known_issues.yaml"
#: Trees scanned by ``--check`` for ids, and the paths under them that are skipped. The fragments this
#: script writes under ``OUT_DIR`` are skipped too (in :func:`cited_ids`); the rest of ``OUT_DIR`` is scanned.
SCAN_ROOTS = (ROOT / "src", ROOT / "docs", ROOT / "examples", ROOT / "scripts", ROOT / "tests")
SCAN_TOP_LEVEL = ("*.md",)
SCAN_SKIP = (CATALOG_DIR,)
SCAN_SKIP_DIRS = {"_build", "__pycache__", ".ipynb_checkpoints", ".pytest_cache"}

HEADER = "<!-- generated by scripts/gen_catalog.py from docs/catalog/*.yaml; do not edit -->"
ID_RE = re.compile(r"\b(EB|KI)-(\d+)\b")

# --- vocabularies --------------------------------------------------------------------------------

ENGINES = {"gsasii": "GSAS-II", "topas": "TOPAS", "easydiffraction": "easydiffraction", "all": "all engines"}
#: Topic -> heading (sentence case), in rendering order.
TOPICS = {
    "space-groups": "Space groups",
    "sites": "Special positions and sites",
    "cell-and-adps": "Cell, ADPs and occupancy",
    "scattering": "Scattering types",
    "names": "Names",
    "bounds": "Bounds and limits",
    "defaults": "Defaults",
    "profile": "Peak profile and instrument",
    "preferred-orientation": "Preferred orientation",
    "data": "Data and the fit window",
    "refinement": "Refinement, convergence and failures",
    "statistics": "Statistics",
    "calculators": "Calculators",
    "platform": "Platform and installation",
}
#: EB status -> (badge role, badge text).
EB_STATUSES = {
    "handled": ("bdg-success", "handled"),
    "warned": ("bdg-warning", "warned"),
    "documented": ("bdg-secondary", "documented"),
    "fixed-upstream": ("bdg-info", "fixed upstream"),
}
#: KI status -> (badge role, section heading), in rendering order.
KI_STATUSES = {
    "open": ("bdg-danger", "Open"),
    "accepted": ("bdg-warning", "Accepted"),
    "watch": ("bdg-info", "Watch"),
    "resolved": ("bdg-success", "Resolved"),
    "withdrawn": ("bdg-secondary", "Withdrawn"),
}
KI_SEVERITIES = ("critical", "major", "minor", "nit")

EB_REQUIRED = ("id", "engine", "versions", "topic", "title", "engine_does", "powderline_does", "you_see", "status")
EB_OPTIONAL = ("seen_in", "note")
KI_REQUIRED = ("id", "title", "status", "what_happens", "what_to_do")
KI_OPTIONAL = ("severity", "applies_to")

# --- loading and validation ----------------------------------------------------------------------


class CatalogError(Exception):
    """The catalogue breaks one of its own rules."""


def _id_key(entry_id: str) -> tuple[str, int]:
    prefix, number = entry_id.split("-")
    return prefix, int(number)


def _label(entry_id: str) -> str:
    return entry_id.lower()


def _load(path: Path) -> list[dict]:
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(data, list):
        raise CatalogError(f"{path.name}: the file must be a YAML list of entries")
    return data


def _check_entries(entries: list[dict], *, name: str, prefix: str, required: tuple, optional: tuple) -> list[str]:
    problems: list[str] = []
    seen: set[str] = set()
    for i, e in enumerate(entries):
        where = f"{name} entry {i + 1}"
        if not isinstance(e, dict):
            problems.append(f"{where}: not a mapping")
            continue
        eid = e.get("id")
        if isinstance(eid, str):
            where = f"{name} {eid}"
        if not isinstance(eid, str) or not re.fullmatch(rf"{prefix}-\d{{2,}}", eid):
            problems.append(f"{where}: id must look like {prefix}-NN, got {eid!r}")
        elif eid in seen:
            problems.append(f"{where}: duplicate id")
        else:
            seen.add(eid)
        for key in required:
            if key not in e:
                problems.append(f"{where}: missing field {key!r}")
        for key in e:
            if key not in required and key not in optional:
                problems.append(f"{where}: unknown field {key!r}")
        for key, value in e.items():
            if key in ("you_see", "seen_in"):
                if not isinstance(value, list) or not all(isinstance(v, str) and v.strip() for v in value):
                    problems.append(f"{where}: {key} must be a list of non-empty strings")
            elif not isinstance(value, str) or not value.strip():
                problems.append(f"{where}: {key} must be a non-empty string")
    return problems


def _known_signal(item: str) -> bool:
    """A ``you_see`` item: a warning code, a failure reason, or a validation error (optionally naming its type)."""
    from powderline.exceptions import WARNING_CODES
    from powderline.results import REASONS
    return item in WARNING_CODES or item in REASONS or item.startswith("validation error")


def validate(eb: list[dict], ki: list[dict]) -> list[str]:
    """Every rule of the catalogue; returns the problems (empty when valid)."""
    problems = _check_entries(eb, name="engine_behaviour.yaml", prefix="EB", required=EB_REQUIRED,
                              optional=EB_OPTIONAL)
    problems += _check_entries(ki, name="known_issues.yaml", prefix="KI", required=KI_REQUIRED,
                               optional=KI_OPTIONAL)
    if problems:
        return problems
    for e in eb:
        if e["engine"] not in ENGINES:
            problems.append(f"{e['id']}: engine {e['engine']!r} is not one of {sorted(ENGINES)}")
        if e["topic"] not in TOPICS:
            problems.append(f"{e['id']}: topic {e['topic']!r} is not one of {list(TOPICS)}")
        if e["status"] not in EB_STATUSES:
            problems.append(f"{e['id']}: status {e['status']!r} is not one of {list(EB_STATUSES)}")
        for item in e["you_see"]:
            if not _known_signal(item):
                problems.append(f"{e['id']}: you_see item {item!r} is not a warning code, a failure reason, "
                                "or 'validation error ...'")
    for e in ki:
        if e["status"] not in KI_STATUSES:
            problems.append(f"{e['id']}: status {e['status']!r} is not one of {list(KI_STATUSES)}")
        if "severity" in e and e["severity"] not in KI_SEVERITIES:
            problems.append(f"{e['id']}: severity {e['severity']!r} is not one of {list(KI_SEVERITIES)}")
        if "severity" not in e and e["status"] != "withdrawn":
            problems.append(f"{e['id']}: missing field 'severity' (only a withdrawn entry may leave it out)")
    # every id cited inside an entry's text must have an entry
    known = {e["id"] for e in eb} | {e["id"] for e in ki}
    for e in eb + ki:
        for key, value in e.items():
            if key == "id":
                continue
            for text in value if isinstance(value, list) else [value]:
                for m in ID_RE.finditer(text):
                    if m.group(0) not in known:
                        problems.append(f"{e['id']}: {key} cites {m.group(0)}, which has no entry")
    return problems


# --- rendering -----------------------------------------------------------------------------------


def _link_ids(text: str, self_id: str) -> str:
    """Turn every cited ``EB-NN`` / ``KI-NN`` (other than the entry's own) into a ``{ref}`` link."""

    def repl(m: re.Match) -> str:
        cited = m.group(0)
        return cited if cited == self_id else f"{{ref}}`{cited} <{_label(cited)}>`"

    return ID_RE.sub(repl, " ".join(text.split()))


def _code(item: str) -> str:
    """A bare code (``easydiffraction_negative_width``) in backticks; anything else as written."""
    return f"`{item}`" if re.fullmatch(r"[a-z][a-z0-9_]*", item) else item


def render_eb_entry(e: dict) -> list[str]:
    role, text = EB_STATUSES[e["status"]]
    does = "What happens" if e["engine"] == "all" else f"{ENGINES[e['engine']]} does"
    lines = [
        f"({_label(e['id'])})=",
        f"#### {e['id']} · {' '.join(e['title'].split())}",
        "",
        f"{{{role}}}`{text}` · {' '.join(e['versions'].split())}",
        "",
        f"**{does}:** {_link_ids(e['engine_does'], e['id'])}",
        "",
        f"**PowderLine does:** {_link_ids(e['powderline_does'], e['id'])}",
        "",
    ]
    if e["you_see"]:
        lines += [f"**You see:** {', '.join(_code(s) for s in e['you_see'])}", ""]
    if e.get("seen_in"):
        lines += [f"**Seen in:** {', '.join(f'`{s}`' for s in e['seen_in'])}", ""]
    if e.get("note"):
        lines += [f"**Note:** {_link_ids(e['note'], e['id'])}", ""]
    return lines


def render_eb(eb: list[dict], engine: str) -> str:
    entries = [e for e in eb if e["engine"] == engine]
    lines = [HEADER, ""]
    for topic, heading in TOPICS.items():
        group = [e for e in entries if e["topic"] == topic]
        if not group:
            continue
        lines += [f"### {heading}", ""]
        for e in group:
            lines += render_eb_entry(e)
    return "\n".join(lines).rstrip("\n") + "\n"


def render_known_issues(ki: list[dict]) -> str:
    lines = [HEADER, ""]
    for status, (role, heading) in KI_STATUSES.items():
        group = sorted((e for e in ki if e["status"] == status), key=lambda e: _id_key(e["id"]))
        if not group:
            continue
        lines += [f"## {heading}", ""]
        for e in group:
            meta = [f"{{{role}}}`{status}`"] + [e[k] for k in ("severity", "applies_to") if k in e]
            lines += [
                f"({_label(e['id'])})=",
                f"### {e['id']} · {' '.join(e['title'].split())}",
                "",
                " · ".join(meta),
                "",
                f"**What happens:** {_link_ids(e['what_happens'], e['id'])}",
                "",
                f"**What to do:** {_link_ids(e['what_to_do'], e['id'])}",
                "",
            ]
    return "\n".join(lines).rstrip("\n") + "\n"


def render_ids(eb: list[dict], ki: list[dict]) -> str:
    def ref(entry_id: str) -> str:
        return f"{{ref}}`{entry_id} <{_label(entry_id)}>`"

    def cell(text: str) -> str:
        return " ".join(text.split()).replace("|", "\\|")

    lines = [HEADER, "", "## Engine behaviors", "", "| ID | Engine | Title | Status |", "|---|---|---|---|"]
    for e in sorted(eb, key=lambda e: _id_key(e["id"])):
        lines.append(f"| {ref(e['id'])} | {ENGINES[e['engine']]} | {cell(e['title'])} | "
                     f"{EB_STATUSES[e['status']][1]} |")
    lines += ["", "## Known issues", "", "| ID | Applies to | Title | Status |", "|---|---|---|---|"]
    for e in sorted(ki, key=lambda e: _id_key(e["id"])):
        lines.append(f"| {ref(e['id'])} | {cell(e.get('applies_to', '—'))} | {cell(e['title'])} | {e['status']} |")
    return "\n".join(lines) + "\n"


def fragments(eb: list[dict], ki: list[dict]) -> dict[str, str]:
    files = {f"eb_{engine}.md": render_eb(eb, engine) for engine in ENGINES}
    files["ids.md"] = render_ids(eb, ki)
    files["known_issues.md"] = render_known_issues(ki)
    return files


# --- the id scan (--check) -----------------------------------------------------------------------


def _scanned_files(roots):
    for root in roots:
        yield from sorted(root.rglob("*"))
    for pattern in SCAN_TOP_LEVEL:
        yield from sorted(ROOT.glob(pattern))


def cited_ids(roots=SCAN_ROOTS, written=()) -> tuple[dict[str, str], int]:
    """Every ``EB-NN`` / ``KI-NN`` in the text files under ``roots`` and the top-level files: id -> first
    ``path:line``. ``written`` are the paths this script writes, which are skipped."""
    found: dict[str, str] = {}
    n_files = 0
    skip_files = {Path(p).resolve() for p in written}
    for path in _scanned_files(roots):
        if not path.is_file() or SCAN_SKIP_DIRS.intersection(path.parts):
            continue
        if path.resolve() in skip_files or any(path == skip or skip in path.parents for skip in SCAN_SKIP):
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue  # binary or unreadable: not a place an id is written
        n_files += 1
        for lineno, line in enumerate(text.splitlines(), 1):
            for m in ID_RE.finditer(line):
                shown = path.relative_to(ROOT) if ROOT in path.parents else path
                found.setdefault(m.group(0), f"{shown.as_posix()}:{lineno}")
    return found, n_files


# --- main ----------------------------------------------------------------------------------------


def _shown(path: Path) -> str:
    """``path`` relative to the repository, with forward slashes, where it lies inside it."""
    try:
        return path.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return str(path)



def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if a committed fragment is stale or extra, or a cited id has no entry")
    ap.add_argument("--out-dir", type=Path, default=OUT_DIR)
    args = ap.parse_args(argv)

    try:
        eb, ki = _load(EB_FILE), _load(KI_FILE)
    except (CatalogError, yaml.YAMLError) as exc:
        print(f"catalog-check: cannot read the catalogue: {exc}", file=sys.stderr)
        return 1
    problems = validate(eb, ki)
    if problems:
        print("catalog-check: the catalogue is invalid:\n  " + "\n  ".join(problems), file=sys.stderr)
        return 1

    files = fragments(eb, ki)
    if not args.check:
        args.out_dir.mkdir(parents=True, exist_ok=True)
        for name, text in files.items():
            path = args.out_dir / name
            with open(path, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text)
            print(f"wrote {_shown(path)}")
        return 0

    status = 0
    stale = [args.out_dir / name for name, text in files.items()
             if not (args.out_dir / name).exists() or (args.out_dir / name).read_text(encoding="utf-8") != text]
    if stale:
        print("stale (regenerate with `pixi run python scripts/gen_catalog.py`): "
              + ", ".join(_shown(p) for p in stale), file=sys.stderr)
        status = 1
    extra = sorted(p for p in args.out_dir.glob("eb_*.md") if p.name not in files)
    if extra:
        print("fragments this script does not write (delete them): " + ", ".join(_shown(p) for p in extra),
              file=sys.stderr)
        status = 1
    known = {e["id"] for e in eb} | {e["id"] for e in ki}
    cited, n_files = cited_ids(written=[args.out_dir / name for name in files])
    missing = sorted((i for i in cited if i not in known), key=_id_key)
    if missing:
        print("ids without a catalogue entry (add them to docs/catalog/*.yaml): "
              + ", ".join(f"{i} (first at {cited[i]})" for i in missing), file=sys.stderr)
        status = 1
    if status:
        return status
    try:
        shown = args.out_dir.resolve().relative_to(Path.cwd().resolve())
    except ValueError:
        shown = args.out_dir
    print(f"catalog-check: {len(files)} files under {shown} match docs/catalog ({len(eb)} EB, {len(ki)} KI); "
          f"the {len(cited)} ids cited in {n_files} scanned files all have entries")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
